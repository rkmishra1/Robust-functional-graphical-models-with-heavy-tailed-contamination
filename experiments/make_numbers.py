"""Generate manuscript/pilot_numbers.tex and manuscript/pilot_table.tex
from results/*.csv and results/pilot_meta.json."""
import os, json
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RES = os.path.join(ROOT, "results")
MANU = os.path.join(ROOT, "manuscript")

meta = json.load(open(os.path.join(RES, "pilot_meta.json")))
vd = meta["verdict"]
summ = pd.read_csv(os.path.join(RES, "summary_amplitude.csv"))
summ = summ.set_index(["method", "eps"])

fdrop = 100 * (vd["f1g0"] - vd["f1g10"]) / max(vd["f1g0"], 1e-9)
stab_cut = 100 * (vd["jg10"] - vd["jt10"]) / max(vd["jg10"], 1e-9)
verdict = "GO" if (vd["d1"] and vd["d2"] and vd["d3"]) else "REVISIT"

verdict_sentence = (
    f"At $\\varepsilon=0.10$ the Gaussian functional graphical lasso selects "
    f"{vd['eg10']:.0f} of {66} possible edges (clean fit: {vd['eg0']:.0f}) and its "
    f"operator-norm error inflates by {100*vd['op_infl']:.0f}\\%, with selection "
    f"instability {vd['jg10']:.2f}; the t-process EM stays at {vd['et10']:.0f} edges "
    f"(clean: {vd['et0']:.0f}), with instability {vd['jt10']:.2f} "
    f"({stab_cut:.0f}\\% lower) and F1 {vd['f1t10']:.2f} against its clean "
    f"{vd['f1t0']:.2f}. The pilot therefore yields a \\textbf{{{verdict}}} decision: "
    + ("the phenomenon is real and the prototype stabilizes it." if verdict == "GO"
       else "the phenomenon or the fix needs strengthening before the full study.")
)

with open(os.path.join(MANU, "pilot_numbers.tex"), "w") as f:
    f.write("% AUTO-GENERATED by experiments/make_numbers.py -- do not edit\n")
    f.write(f"\\newcommand{{\\NumEdgesTrue}}{{{meta['n_true_edges']}}}\n")
    f.write(f"\\newcommand{{\\NumMinEig}}{{0.99}}\n")
    f.write(f"\\newcommand{{\\NumLamG}}{{{meta['lam_fglasso']:.2f}}}\n")
    f.write(f"\\newcommand{{\\NumLamT}}{{{meta['lam_t_em']:.2f}}}\n")
    f.write(f"\\newcommand{{\\NumFdropPct}}{{{fdrop:.0f}}}\n")
    f.write(f"\\newcommand{{\\NumOpErrInfl}}{{{100*vd['op_infl']:.0f}}}\n")
    f.write(f"\\newcommand{{\\NumSatPct}}{{{100*vd['sat']:.0f}}}\n")
    f.write(f"\\newcommand{{\\NumStabFg}}{{{vd['jg10']:.2f}}}\n")
    f.write(f"\\newcommand{{\\NumStabTem}}{{{vd['jt10']:.2f}}}\n")
    f.write(f"\\newcommand{{\\NumStabCut}}{{{stab_cut:.0f}}}\n")
    f.write(f"\\newcommand{{\\NumFoneG}}{{{vd['f1g0']:.2f}}}\n")
    f.write(f"\\newcommand{{\\NumFoneT}}{{{vd['f1t0']:.2f}}}\n")
    f.write(f"\\newcommand{{\\NumVerdict}}{{{verdict}}}\n")
    f.write(f"\\newcommand{{\\NumStabImproveDesc}}{{cuts selection instability "
            f"by {stab_cut:.0f}\\% (Jaccard {vd['jg10']:.2f}$\\to${vd['jt10']:.2f})}}\n")
    f.write(f"\\newcommand{{\\NumVerdictSentence}}{{{verdict_sentence}}}\n")

# ---- table -----------------------------------------------------------------
labels = {"fglasso": "fGLasso (Gaussian)", "t_em": "f t-EM (robust)"}
lines = [
    r"\begin{tabular}{llcccccc}", r"\toprule",
    r"Method & $\varepsilon$ & F1 & Precision & Recall & Instability & Edges \\",
    r"\midrule",
]
labels["altt_em"] = "f alt-t EM (model b)"
for method in ["fglasso", "t_em", "altt_em"]:
    for i, eps in enumerate([0.0, 0.05, 0.10, 0.15]):
        row = summ.loc[(method, eps)]
        name = labels[method] if i == 0 else ""
        lines.append(
            f"{name} & {eps:.2f} & {row['f1_mean']:.2f} ({row['f1_std']:.2f}) & "
            f"{row['precision_mean']:.2f} & {row['recall_mean']:.2f} & "
            f"{row['jaccard_mean']:.2f} & {row['n_edges_est_mean']:.1f} \\\\"
        )
    if method == "fglasso":
        lines.append(r"\midrule")
lines += [r"\bottomrule", r"\end{tabular}"]
with open(os.path.join(MANU, "pilot_table.tex"), "w") as f:
    f.write("% AUTO-GENERATED -- do not edit\n" + "\n".join(lines) + "\n")

print(f"verdict={verdict}  op-err inflation={100*vd['op_infl']:.0f}%  "
      f"saturation={100*vd['sat']:.0f}%  instability {vd['jg10']:.2f} -> {vd['jt10']:.2f}")
print("wrote pilot_numbers.tex, pilot_table.tex")
